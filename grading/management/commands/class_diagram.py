"""Write docs/classes.d2 from the grading models.

The diagram is generated so it cannot drift from the code. A test compares the
committed file with this command's output, so after changing a model run:

    python manage.py class_diagram
    d2 --layout elk --font-regular SchibstedGrotesk-Regular.ttf \
       --font-bold SchibstedGrotesk-Bold.ttf docs/classes.d2 docs/classes.svg
"""

import inspect
from pathlib import Path

from django.apps import apps
from django.conf import settings
from django.core.management.base import BaseCommand
from django.core.validators import MaxValueValidator, MinValueValidator
from django.db import models

DEFAULT_OUTPUT = Path(settings.BASE_DIR) / "docs" / "classes.d2"

HEADER = """\
# Generated by `python manage.py class_diagram`. Do not edit by hand.
# Render with Schibsted Grotesk (decision 0006):
#   d2 --layout elk --font-regular SchibstedGrotesk-Regular.ttf \\
#      --font-bold SchibstedGrotesk-Bold.ttf docs/classes.d2 docs/classes.svg

vars: {
  d2-config: {
    layout-engine: elk
    pad: 48
  }
}

direction: right
"""

# For D2 class shapes, fill paints the header and stroke paints the body.
CLASS_STYLE = """\
  style: {
    fill: "#0D1117"
    stroke: "#FFFFFF"
    font-color: "#FFFFFF"
    font-size: 16
  }"""


def _range(field):
    low = high = None
    # Only validators written on the model, not Django's built-in int limits.
    for v in field._validators:
        if isinstance(v, MinValueValidator):
            low = v.limit_value
        elif isinstance(v, MaxValueValidator):
            high = v.limit_value
    if low is None and high is None:
        return ""
    if high is None:
        return f" >= {low}"
    return f" {low}..{high}"


def field_type(field):
    if field.choices:
        values = ", ".join(str(v) for v, _ in field.choices)
        return f"choice({values})"
    if isinstance(field, models.DecimalField):
        return f"Decimal({field.max_digits},{field.decimal_places}){_range(field)}"
    if isinstance(field, models.CharField):
        return f"str({field.max_length})" + (" unique" if field.unique else "")
    if isinstance(field, models.TextField):
        return "text"
    if isinstance(field, models.IntegerField):
        return f"int{_range(field)}"
    return field.get_internal_type()


def own_methods(model):
    """Public methods and clean() defined on the model itself."""
    names = []
    for name, value in vars(model).items():
        if not inspect.isfunction(value):
            continue
        if name == "clean" or not name.startswith("_"):
            names.append(name)
    return names


def render(app_label="grading"):
    app_models = list(apps.get_app_config(app_label).get_models())
    user_model = apps.get_model(settings.AUTH_USER_MODEL)
    lines = [HEADER]

    for model in app_models:
        lines.append(f"{model.__name__}: {{")
        lines.append("  shape: class")
        for field in model._meta.concrete_fields:
            if field.primary_key or field.is_relation:
                continue
            lines.append(f'  "{field.name}": "{field_type(field)}"')
        for name in own_methods(model):
            lines.append(f'  "{name}()": ""')
        lines.append(CLASS_STYLE)
        lines.append("}")
        lines.append("")

    lines.append(f"{user_model.__name__}: {{")
    lines.append("  shape: class")
    lines.append(f'  "{user_model.USERNAME_FIELD}": "str (django.contrib.auth)"')
    lines.append(CLASS_STYLE)
    lines.append("}")
    lines.append("")

    # Associations: one line per foreign key, many side -> one side.
    for model in app_models:
        for field in model._meta.concrete_fields:
            if not field.many_to_one:
                continue
            target = field.related_model.__name__
            protect = field.remote_field.on_delete is models.PROTECT
            label = f"{field.name}, PROTECT" if protect else field.name
            color = "#C8102E" if protect else "#41464E"
            lines.append(f'{model.__name__} -> {target}: "{label}" {{')
            lines.append('  source-arrowhead.label: "*"')
            lines.append('  target-arrowhead.label: "1"')
            lines.append(f'  style: {{stroke: "{color}"; stroke-width: 2; font-color: "{color}"}}')
            lines.append("}")

    # Many to many links: many on both sides.
    for model in app_models:
        for field in model._meta.many_to_many:
            target = field.related_model.__name__
            lines.append(f'{model.__name__} -> {target}: "{field.name}" {{')
            lines.append('  source-arrowhead.label: "*"')
            lines.append('  target-arrowhead.label: "*"')
            lines.append('  style: {stroke: "#41464E"; stroke-width: 2; stroke-dash: 4; font-color: "#41464E"}')
            lines.append("}")

    return "\n".join(lines) + "\n"


class Command(BaseCommand):
    help = "Write the class diagram (D2 source) generated from the grading models."

    def add_arguments(self, parser):
        parser.add_argument("--output", default=str(DEFAULT_OUTPUT))

    def handle(self, *args, **options):
        Path(options["output"]).write_text(render(), encoding="utf-8")
        self.stdout.write(f"wrote {options['output']}")
