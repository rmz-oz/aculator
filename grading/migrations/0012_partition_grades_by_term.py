"""Partition grades by term (#33, CSE 321 section 4), the second of two steps.

0011 added the term and the version that sets it on every save. This copies
the grades into a table partitioned by term, in one transaction: a failure
leaves the old table as it was. The term is taken from each grade's offering
while copying, so rows an older version wrote without one are covered too,
and the grade history (#35) gets no rows.

Not reversible; going back means restoring the backup taken before the
deploy (docs/failures.md).
"""

import django.db.models.deletion
from django.db import OperationalError, migrations, models, transaction

VIEWS = ("student_lo_scores", "course_po_scores", "cross_course_po_scores")  # in dependency order

CREATE_TABLE = """
CREATE TABLE grading_grade_new (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    score numeric(6, 2) NOT NULL,
    assessment_id bigint NOT NULL,
    enrollment_id bigint NOT NULL,
    status varchar(10) NOT NULL,
    term_id bigint NOT NULL,
    -- A primary key on a partitioned table must contain the partition key.
    -- Ids still come from one sequence, so they stay unique on their own.
    PRIMARY KEY (id, term_id),
    -- Renamed to uniq_grade once the old table and its index are gone.
    CONSTRAINT uniq_grade_new UNIQUE (enrollment_id, assessment_id, term_id),
    CONSTRAINT grade_score_nonnegative CHECK (score >= 0),
    CONSTRAINT grade_status_valid CHECK (status IN ('graded', 'absent')),
    CONSTRAINT grade_absent_is_zero CHECK (status <> 'absent' OR score = 0)
) PARTITION BY LIST (term_id);

CREATE TABLE grading_grade_part_default PARTITION OF grading_grade_new DEFAULT;
"""

COPY_AND_CHECK = """
INSERT INTO grading_grade_new (id, score, assessment_id, enrollment_id, status, term_id)
SELECT g.id, g.score, g.assessment_id, g.enrollment_id, g.status, o.term_id
FROM grading_grade g
JOIN grading_enrollment e ON e.id = g.enrollment_id
JOIN grading_courseoffering o ON o.id = e.offering_id;

DO $$ BEGIN
    IF (SELECT (count(*), sum(id), sum(score)) FROM grading_grade)
       IS DISTINCT FROM (SELECT (count(*), sum(id), sum(score)) FROM grading_grade_new) THEN
        RAISE EXCEPTION 'Copying the grades into the partitioned table lost or changed rows';
    END IF;
END $$;
"""

TRIGGERS = """
-- A grade's term is its offering's term; the enrollment and the assessment
-- belong to the same offering. On update only when one of those columns
-- really changes: Django writes every column on save, so a score edit would
-- otherwise run the three lookups too.
CREATE FUNCTION grading_grade_check_term() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE enrollment_offering bigint; assessment_offering bigint; offering_term bigint;
BEGIN
    SELECT offering_id INTO enrollment_offering FROM grading_enrollment WHERE id = NEW.enrollment_id;
    SELECT offering_id INTO assessment_offering FROM grading_assessment WHERE id = NEW.assessment_id;
    SELECT term_id INTO offering_term FROM grading_courseoffering WHERE id = enrollment_offering;
    IF enrollment_offering IS DISTINCT FROM assessment_offering OR NEW.term_id IS DISTINCT FROM offering_term THEN
        RAISE EXCEPTION 'A grade must be in the term and offering of its enrollment and assessment';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER grading_grade_check_term_insert
BEFORE INSERT ON grading_grade
FOR EACH ROW EXECUTE FUNCTION grading_grade_check_term();

CREATE TRIGGER grading_grade_check_term_update
BEFORE UPDATE OF enrollment_id, assessment_id, term_id ON grading_grade
FOR EACH ROW WHEN (
    NEW.enrollment_id IS DISTINCT FROM OLD.enrollment_id
    OR NEW.assessment_id IS DISTINCT FROM OLD.assessment_id
    OR NEW.term_id IS DISTINCT FROM OLD.term_id
) EXECUTE FUNCTION grading_grade_check_term();

CREATE TRIGGER grading_grade_change_history
AFTER INSERT OR UPDATE OR DELETE ON grading_grade
FOR EACH ROW EXECUTE FUNCTION grading_record_grade_change();

-- Moving an offering, enrollment or assessment that has grades would put
-- those grades in the wrong term.
CREATE FUNCTION grading_grade_guard_parents() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_TABLE_NAME = 'grading_courseoffering' THEN
        IF EXISTS (SELECT 1 FROM grading_enrollment e JOIN grading_grade g ON g.enrollment_id = e.id
                   WHERE e.offering_id = OLD.id) THEN
            RAISE EXCEPTION 'An offering with grades cannot move to another term';
        END IF;
    ELSIF EXISTS (SELECT 1 FROM grading_grade
                  WHERE (TG_TABLE_NAME = 'grading_enrollment' AND enrollment_id = OLD.id)
                     OR (TG_TABLE_NAME = 'grading_assessment' AND assessment_id = OLD.id)) THEN
        RAISE EXCEPTION '% % has grades and cannot move to another offering', TG_TABLE_NAME, OLD.id;
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER grading_grade_guard_offering BEFORE UPDATE OF term_id ON grading_courseoffering
FOR EACH ROW WHEN (NEW.term_id IS DISTINCT FROM OLD.term_id) EXECUTE FUNCTION grading_grade_guard_parents();
CREATE TRIGGER grading_grade_guard_enrollment BEFORE UPDATE OF offering_id ON grading_enrollment
FOR EACH ROW WHEN (NEW.offering_id IS DISTINCT FROM OLD.offering_id) EXECUTE FUNCTION grading_grade_guard_parents();
CREATE TRIGGER grading_grade_guard_assessment BEFORE UPDATE OF offering_id ON grading_assessment
FOR EACH ROW WHEN (NEW.offering_id IS DISTINCT FROM OLD.offering_id) EXECUTE FUNCTION grading_grade_guard_parents();

-- Every new term gets its own partition. Without this its grades would pile
-- up in DEFAULT, and a partition for that term could not be added later.
CREATE FUNCTION grading_grade_add_partition() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    EXECUTE format('CREATE TABLE IF NOT EXISTS %I PARTITION OF grading_grade FOR VALUES IN (%L)',
                   'grading_grade_part_' || NEW.id, NEW.id);
    RETURN NEW;
END $$;

CREATE TRIGGER grading_term_grade_partition AFTER INSERT ON grading_term
FOR EACH ROW EXECUTE FUNCTION grading_grade_add_partition();

-- A term can only be deleted without grades (PROTECT), so its partition is empty.
CREATE FUNCTION grading_grade_drop_partition() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    EXECUTE format('DROP TABLE IF EXISTS %I', 'grading_grade_part_' || OLD.id);
    RETURN OLD;
END $$;

CREATE TRIGGER grading_term_drop_grade_partition AFTER DELETE ON grading_term
FOR EACH ROW EXECUTE FUNCTION grading_grade_drop_partition();
"""


def partition_grades(apps, schema_editor):
    with schema_editor.connection.cursor() as cursor:
        def fetch(sql, params=()):
            cursor.execute(sql, params)
            return cursor.fetchall()

        # The score views read grading_grade. Keep their exact current
        # definitions and indexes from the catalog, recreate them afterwards.
        views = []
        for name in VIEWS:
            [(definition,)] = fetch("SELECT pg_get_viewdef(%s::regclass, true)", [name])
            indexes = [row[0] for row in fetch("SELECT indexdef FROM pg_indexes WHERE tablename = %s", [name])]
            views.append((name, definition, indexes))

        # Dropping the old table also drops its foreign keys, which needs the
        # parent tables exclusively. Take every lock at once, or a grade import
        # running meanwhile (it reads the parents, then waits for grades)
        # deadlocks with this migration and the deploy fails. A short timeout
        # under deadlock_timeout (1 s) and another try lets the import finish first.
        for attempt in range(600):
            try:
                with transaction.atomic(using=schema_editor.connection.alias):
                    cursor.execute("SET LOCAL lock_timeout = '100ms'")
                    cursor.execute(
                        "LOCK TABLE grading_enrollment, grading_assessment, grading_courseoffering, grading_term,"
                        " grading_grade IN ACCESS EXCLUSIVE MODE"
                    )
                    for name in reversed(VIEWS):
                        cursor.execute(f"DROP MATERIALIZED VIEW {name}")
                break
            except OperationalError:
                continue
        else:
            raise RuntimeError("Could not lock the grade tables for a minute; deploy again when nobody is entering grades")
        cursor.execute("SET LOCAL lock_timeout = 0")

        cursor.execute(CREATE_TABLE)
        for (term_id,) in fetch("SELECT id FROM grading_term ORDER BY id"):
            cursor.execute(
                f"CREATE TABLE grading_grade_part_{int(term_id)} PARTITION OF grading_grade_new FOR VALUES IN ({int(term_id)})"
            )
        cursor.execute(COPY_AND_CHECK)

        # Ids continue after the highest ever handed out, so a deleted
        # grade's id is not given to a new grade (its history keeps it).
        [(old_sequence,)] = fetch("SELECT pg_get_serial_sequence('grading_grade', 'id')")
        [(last_old,)] = fetch(f"SELECT CASE WHEN is_called THEN last_value ELSE 0 END FROM {old_sequence}")
        [(highest,)] = fetch(
            "SELECT GREATEST(%s, (SELECT max(id) FROM grading_grade), (SELECT max(grade_id) FROM grading_gradechange))",
            [last_old],
        )
        cursor.execute(
            "SELECT setval(pg_get_serial_sequence('grading_grade_new', 'id'), %s, %s)",
            [max(highest or 0, 1), bool(highest)],
        )

        cursor.execute("DROP TABLE grading_grade")
        cursor.execute("ALTER TABLE grading_grade_new RENAME TO grading_grade")
        cursor.execute("ALTER TABLE grading_grade RENAME CONSTRAINT uniq_grade_new TO uniq_grade")
        cursor.execute("ALTER INDEX grading_grade_new_pkey RENAME TO grading_grade_pkey")
        cursor.execute("ALTER SEQUENCE grading_grade_new_id_seq RENAME TO grading_grade_id_seq")
        # Added after the copy: checked in one query each instead of row by row.
        for column, table in (("assessment_id", "grading_assessment"), ("enrollment_id", "grading_enrollment"),
                              ("term_id", "grading_term")):
            cursor.execute(
                f"ALTER TABLE grading_grade ADD CONSTRAINT grading_grade_{column}_fkey FOREIGN KEY ({column}) "
                f"REFERENCES {table} (id) DEFERRABLE INITIALLY DEFERRED"
            )
        cursor.execute("CREATE INDEX grading_grade_enrollment_id ON grading_grade (enrollment_id)")
        cursor.execute("CREATE INDEX grading_grade_assessment_id ON grading_grade (assessment_id)")
        cursor.execute(TRIGGERS)

        # Created WITH DATA, so this also fills them.
        for name, definition, indexes in views:
            cursor.execute(f"CREATE MATERIALIZED VIEW {name} AS {definition}")
            for index in indexes:
                cursor.execute(index)
        # Autovacuum never analyzes a partitioned table itself, only its partitions.
        cursor.execute("ANALYZE grading_grade")


