-- New partitioned Grade table
-- This is a staging table; the original grading_grade is unchanged.

CREATE TABLE grading_grade_partitioned (
    id bigint GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME grading_grade_partitioned_id_seq
    ),
    enrollment_id bigint NOT NULL,
    assessment_id bigint NOT NULL,
    term_id bigint NOT NULL,
    status varchar(10) NOT NULL DEFAULT 'graded',
    score numeric(6,2) NOT NULL,

    CONSTRAINT grading_grade_partitioned_pkey
        PRIMARY KEY (id, term_id),

    CONSTRAINT grading_grade_partitioned_unique
        UNIQUE (enrollment_id, assessment_id, term_id),

    CONSTRAINT grading_grade_partitioned_score_nonnegative
        CHECK (score >= 0),

    CONSTRAINT grading_grade_partitioned_status_valid
        CHECK (status IN ('graded', 'absent')),

    CONSTRAINT grading_grade_partitioned_absent_zero
        CHECK (status <> 'absent' OR score = 0)
)
PARTITION BY LIST (term_id);
-- Create one partition for each existing term.
DO $$
DECLARE
    t RECORD;
BEGIN
    FOR t IN
        SELECT id, year, season
        FROM grading_term
        ORDER BY year, season
    LOOP
        EXECUTE format(
            'CREATE TABLE %I PARTITION OF grading_grade_partitioned FOR VALUES IN (%L)',
            'grading_grade_part_' || t.id,
            t.id
        );
    END LOOP;
END
$$;

-- Handle terms added after this migration.
CREATE TABLE grading_grade_part_default
    PARTITION OF grading_grade_partitioned DEFAULT;
-- Preserve foreign key relationships.
ALTER TABLE grading_grade_partitioned
    ADD CONSTRAINT grading_grade_partitioned_enrollment_fk
        FOREIGN KEY (enrollment_id)
        REFERENCES grading_enrollment(id)
        DEFERRABLE INITIALLY DEFERRED,

    ADD CONSTRAINT grading_grade_partitioned_assessment_fk
        FOREIGN KEY (assessment_id)
        REFERENCES grading_assessment(id)
        DEFERRABLE INITIALLY DEFERRED,

    ADD CONSTRAINT grading_grade_partitioned_term_fk
        FOREIGN KEY (term_id)
        REFERENCES grading_term(id)
        DEFERRABLE INITIALLY DEFERRED;
    -- Validate the term and course offering of each grade.
CREATE OR REPLACE FUNCTION validate_partitioned_grade()
RETURNS trigger AS $$
DECLARE
    expected_term_id bigint;
    enrollment_offering_id bigint;
    assessment_offering_id bigint;
BEGIN
    SELECT offering_id
    INTO enrollment_offering_id
    FROM grading_enrollment
    WHERE id = NEW.enrollment_id;

    SELECT offering_id
    INTO assessment_offering_id
    FROM grading_assessment
    WHERE id = NEW.assessment_id;

    SELECT term_id
    INTO expected_term_id
    FROM grading_courseoffering
    WHERE id = enrollment_offering_id;

    IF enrollment_offering_id IS DISTINCT FROM assessment_offering_id THEN
        RAISE EXCEPTION
            'Grade enrollment and assessment must belong to the same offering';
    END IF;

    IF NEW.term_id IS DISTINCT FROM expected_term_id THEN
        RAISE EXCEPTION
            'Grade term_id does not match enrollment term_id';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER validate_partitioned_grade_trigger
BEFORE INSERT OR UPDATE ON grading_grade_partitioned
FOR EACH ROW
EXECUTE FUNCTION validate_partitioned_grade();
-- Registry for globally unique Grade IDs.
CREATE TABLE grading_grade_id_registry (
    id bigint PRIMARY KEY
);

-- Reserve each Grade ID before insertion.
CREATE OR REPLACE FUNCTION register_partitioned_grade_id()
RETURNS trigger AS $$
BEGIN
    INSERT INTO grading_grade_id_registry (id)
    VALUES (NEW.id);

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER register_partitioned_grade_id_trigger
BEFORE INSERT ON grading_grade_partitioned
FOR EACH ROW
EXECUTE FUNCTION register_partitioned_grade_id();

-- Register existing Grade IDs before copying the records.
INSERT INTO grading_grade_id_registry (id)
SELECT id
FROM grading_grade;
-- Disable ID registration during the initial data migration.
ALTER TABLE grading_grade_partitioned
DISABLE TRIGGER register_partitioned_grade_id_trigger;

-- Copy existing grades into their term partitions.
INSERT INTO grading_grade_partitioned (
    id,
    enrollment_id,
    assessment_id,
    term_id,
    status,
    score
)
SELECT
    id,
    enrollment_id,
    assessment_id,
    term_id,
    status,
    score
FROM grading_grade;

-- Re-enable ID registration for future inserts.
ALTER TABLE grading_grade_partitioned
ENABLE TRIGGER register_partitioned_grade_id_trigger;
-- Prevent changing an existing Grade ID.
CREATE OR REPLACE FUNCTION prevent_partitioned_grade_id_update()
RETURNS trigger AS $$
BEGIN
    IF NEW.id IS DISTINCT FROM OLD.id THEN
        RAISE EXCEPTION
            'Grade ID cannot be changed after creation';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER prevent_partitioned_grade_id_update_trigger
BEFORE UPDATE ON grading_grade_partitioned
FOR EACH ROW
EXECUTE FUNCTION prevent_partitioned_grade_id_update();
-- Prevent changing the partition key of an existing Grade.
CREATE OR REPLACE FUNCTION prevent_partitioned_grade_term_update()
RETURNS trigger AS $$
BEGIN
    IF NEW.term_id IS DISTINCT FROM OLD.term_id THEN
        RAISE EXCEPTION
            'Grade term_id cannot be changed after creation';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER prevent_partitioned_grade_term_update_trigger
BEFORE UPDATE ON grading_grade_partitioned
FOR EACH ROW
EXECUTE FUNCTION prevent_partitioned_grade_term_update();
-- Continue generating IDs after the highest existing Grade ID.
SELECT setval(
    'grading_grade_partitioned_id_seq',
    COALESCE((SELECT MAX(id) FROM grading_grade_partitioned), 1),
    (SELECT COUNT(*) > 0 FROM grading_grade_partitioned)
);
-- Verify that every existing Grade was copied correctly.
DO $$
BEGIN
    IF EXISTS (
        SELECT id, enrollment_id, assessment_id, term_id, status, score
        FROM grading_grade

        EXCEPT

        SELECT id, enrollment_id, assessment_id, term_id, status, score
        FROM grading_grade_partitioned
    )
    OR EXISTS (
        SELECT id, enrollment_id, assessment_id, term_id, status, score
        FROM grading_grade_partitioned

        EXCEPT

        SELECT id, enrollment_id, assessment_id, term_id, status, score
        FROM grading_grade
    )
    OR (
        SELECT COUNT(*) FROM grading_grade
    ) <> (
        SELECT COUNT(*) FROM grading_grade_partitioned
    )
    THEN
        RAISE EXCEPTION
            'Grade migration verification failed: data mismatch';
    END IF;
END;
$$;
